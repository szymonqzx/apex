/*
 * drivers/apex/apex.c
 *
 * apex control plane (Redmi Note 12 4G, SM6225-AD)
 *
 * Provides:
 *   - /proc/apex/* read-only status surface (0444)
 *   - /proc/apex/policy write surface (0220, CAP_SYS_ADMIN required):
 *     "screen_off", "screen_on", "charge 0|1", "audio 0|1", "fg <uid>", "game 0|1"
 *   - /proc/apex/gaming read-write for gaming mode toggle (0644, CAP_SYS_ADMIN)
 *   - /proc/apex/governor read-only for tunable status
 *   - /proc/apex/wakealarm read-write (0644) for arming PMIC wake via epoch seconds
 *   - /proc/apex/version read-only for build version info
 *   - /proc/apex/stats read-only for cumulative statistics
 *   - automatic power_supply (charging) detection via notifier
 *   - battery status (capacity, health, temp) in /proc/apex/state
 *   - thermal zone monitoring with automatic CPU frequency capping
 *   - GPU devfreq control (screen_off/gaming modes)
 *   - 5-minute health tick (subsystem checks, logs to incident ring)
 *   - 7-day routine learner (moving average patterns for thermal/screen-off)
 *   - panic notifier: appends panic info to apex incident ring
 *   - RTC wakealarm: write epoch seconds to arm the PMIC wake
 *
 * Owns /proc/apex directory creation. Other apex modules (watchdog) must
 * use apex_get_proc_dir() to get the existing directory pointer rather than
 * calling proc_mkdir("apex", NULL) themselves.
 */

