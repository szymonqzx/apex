/* Compute the 4-bit decision index from current state */
static inline unsigned int apex_decision_index(void)
{
	return ((unsigned int)apex_state.screen_on << 3) |
	       ((unsigned int)apex_state.charging << 2) |
	       ((unsigned int)apex_state.audio_active << 1) |
	       ((unsigned int)(apex_state.foreground_uid != 0));
}

/* Get the current decision table entry (gaming overrides) */
static const struct apex_decision_entry *apex_current_decision(void)
{
	unsigned int idx = apex_decision_index();

	/* Gaming mode overrides everything — always use performance policy */
	if (apex_state.gaming_active) {
		static const struct apex_decision_entry gaming_entry = {
			.row = APEX_ROW_GAMING, .gpu_performance = true,
			.gpu_powersave = false, .gov_gaming = true,
			.gov_screen_off = false, .sensor_rate_hz = 200,
			.bt_scan_enabled = true, .wifi_multicast = true,
		};
		return &gaming_entry;
	}

	return &apex_decision_table[idx];
}

