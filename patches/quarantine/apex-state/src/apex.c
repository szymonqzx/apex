/* Local trim: strip trailing whitespace in-place (kernel-space version). */
static void apex_trim(char *s)
{
	size_t len = strlen(s);
	while (len > 0 && (s[len - 1] == '\n' || s[len - 1] == '\r' ||
	       s[len - 1] == ' ' || s[len - 1] == '\t'))
		s[--len] = '\0';
}

