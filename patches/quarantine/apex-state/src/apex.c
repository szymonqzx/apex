static int apex_proc_incidents_show(struct seq_file *m, void *v)
{
	unsigned int i;
	unsigned long flags;

	/* Use irqsave variant to match the writer — the writer may be
	 * called from interrupt context (panic notifier). */
	spin_lock_irqsave(&apex_state.incident_lock, flags);
	for (i = 0; i < apex_state.incident_count; i++) {
		unsigned int idx = (apex_state.incident_head + i) % APEX_INCIDENT_RING_SIZE;

		if (apex_state.incidents[idx])
			seq_printf(m, "[%u] %s\n", i, apex_state.incidents[idx]);
	}
	spin_unlock_irqrestore(&apex_state.incident_lock, flags);
	return 0;
}

